function rx(source, flags = "i") {
  let out = "";
  for (let i = 0;i < source.length; i++) {
    const ch = source[i];
    if (ch !== "\\") {
      out += ch;
      continue;
    }
    const next = source[i + 1];
    if (next !== "b") {
      out += ch + next;
      i++;
      continue;
    }
    const after = source[i + 2] ?? "", before = source[i - 1] ?? "";
    const literal = (c) => new RegExp(`^${W}$`).test(c);
    out += literal(after) && before !== "\\" ? START : literal(before) && !/\\[A-Za-z]$/.test(source.slice(i - 2, i)) ? END : BOUNDARY;
    i++;
  }
  return new RegExp(out, flags.replace("u", ""));
}
