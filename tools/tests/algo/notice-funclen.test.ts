// NOTICES function-length reader: named functions only, three block readers, precision first.
import { describe, expect, test } from 'bun:test'
import { executeNoticeAlgo } from '../../notice-core'
import { functions, skipFile } from '../../notice/funclen'

const body = (n: number, indent = '  ', line = 'work()') => Array.from({ length: n }, () => indent + line).join('\n')
const span = (text: string, ext: string) => functions(text, ext).map(f => [f.name, f.start, f.end])

describe('braces', () => {
  test('declarations, arrow functions bound to a name and methods count; callbacks and control blocks do not', () => {
    const ts = [
      'function plain(a) {', '  return a', '}',
      'const arrow = async (x: number) => {', '  return x', '}',
      'class Box {', '  method(a) {', '    if (a) {', '      return 1', '    }', '    return 2', '  }', '}',
      'describe("suite", () => {', '  it("works", () => {', '    run()', '  })', '})',
      'promise.then(() => {', '  done()', '})',
    ].join('\n')
    expect(span(ts, 'ts')).toEqual([['plain', 1, 3], ['arrow', 4, 6], ['method', 8, 13]])
  })

  test('strings, template text, comments and regex literals hide their braces', () => {
    const js = [
      'function a() {', '  const s = "}"', '  const t = `x ${"{"} }`', '  // }', '  const r = /}/', '  return s', '}',
      'function b() {', '  return 1', '}',
    ].join('\n')
    expect(span(js, 'js')).toEqual([['a', 1, 7], ['b', 8, 10]])
  })

  test('Go, Rust, Swift and Java headers', () => {
    expect(span('func (s *Server) Run(ctx context.Context) error {\n\treturn nil\n}\n', 'go')).toEqual([['Run', 1, 3]])
    expect(span('pub fn parse(input: &str) -> Result<Ast, Error> {\n    let c = \'}\';\n    Ok(ast)\n}\n', 'rs')).toEqual([['parse', 1, 4]])
    expect(span('final class Cache {\n    func evict(key: String) {\n        drop(key)\n    }\n}\n', 'swift')).toEqual([['evict', 2, 4]])
    expect(span('public class A {\n    public static void main(String[] args) {\n        go();\n    }\n}\n', 'java')).toEqual([['main', 2, 4]])
  })

  test('a function whose closing line does not sit at its header\'s indentation is not reported', () => {
    expect(span('function odd() {\n  work()\n  }\n', 'ts')).toEqual([])
  })
})

describe('indentation and keyword-end', () => {
  test('Python: def with decorators, docstrings that mention def, one-liners and nested defs', () => {
    const py = [
      'def one(): return 1',
      '@decorator',
      'def outer(a,',
      '          b):',
      '    """A docstring that says:',
      '    def not_a_function():',
      '    """',
      '    def inner():',
      '        return a',
      '    return inner',
      '',
      'async def last():',
      '    pass',
    ].join('\n')
    expect(span(py, 'py')).toEqual([['one', 1, 1], ['outer', 3, 10], ['inner', 8, 9], ['last', 12, 13]])
  })

  test('Ruby: def ... end with blocks and heredocs inside', () => {
    const rb = ['class Cask', '  def install(name)', '    items.each do |item|', '      run(item)', '    end', '    text = <<~EOS', '      def fake', '    EOS', '  end', 'end'].join('\n')
    expect(span(rb, 'rb')).toEqual([['install', 2, 9]])
  })
})

describe('files nobody grows by hand', () => {
  test('generated, minified and huge files are skipped', () => {
    expect(skipFile('// @generated by protoc\n' + body(3))).toBe(true)
    expect(skipFile('x'.repeat(5000) + '\n'.repeat(10))).toBe(true)
    expect(skipFile('const a = 1\n')).toBe(false)
    expect(functions('// DO NOT EDIT\nfunction a() {\n}\n', 'ts')).toEqual([])
  })
})

describe('the long-function op (400 lines)', () => {
  const header = 'function big() {\n'
  const make = (n: number) => header + body(n) + '\n}\n'
  const touched = (text: string) => Array.from({ length: text.split('\n').length }, (_, i) => i + 1)

  test('an edit that leaves a function over 400 lines and made it longer is reported', () => {
    const after = make(405), before = make(398)
    expect(executeNoticeAlgo({ op: 'long', path: 'src/a.ts', limit: 400, before, after, touched: [200] })).toEqual({ name: 'big', lines: 407 })
  })

  test('already long and not longer, short, or an edit elsewhere in the file: nothing', () => {
    expect(executeNoticeAlgo({ op: 'long', path: 'src/a.ts', limit: 400, before: make(450), after: make(450), touched: [200] })).toBeNull()
    expect(executeNoticeAlgo({ op: 'long', path: 'src/a.ts', limit: 400, before: make(100), after: make(120), touched: [50] })).toBeNull()
    const elsewhere = make(450) + 'function small() {\n  x()\n}\n'
    expect(executeNoticeAlgo({ op: 'long', path: 'src/a.ts', limit: 400, before: make(450), after: elsewhere, touched: [454] })).toBeNull()
  })

  test('a new file over the limit counts; an unsupported extension never does', () => {
    const text = make(450)
    expect(executeNoticeAlgo({ op: 'long', path: 'src/a.ts', limit: 400, before: null, after: text, touched: touched(text) })).toEqual({ name: 'big', lines: 452 })
    expect(executeNoticeAlgo({ op: 'long', path: 'notes.md', limit: 400, before: null, after: text, touched: touched(text) })).toBeNull()
  })
})
