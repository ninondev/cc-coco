#!/usr/bin/env python3
"""Generate hook data and editable pet line packs from source/line-supplements.json.

No network access. --check compares the existing outputs without writing them.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'source/line-supplements.json').read_text())
    outputs = {ROOT / 'source/hooks/line-supplements.ts':
               '// Generated by tools/build-line-supplements.py from source/line-supplements.json.\n'
               + 'export const LINE_SUPPLEMENTS = ' + json.dumps(data, ensure_ascii=False, indent=2) + ' as const\n'}
    for lang, characters in data.items():
        for character, groups in characters.items():
            outputs[ROOT / f'plugin/assets/lines/{character}-supplement-{lang}.txt'] = '\n'.join(
                '\n[' + group + ']\n' + '\n'.join(lines) for group, lines in groups.items()) + '\n'
    stale = []
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    print(f'{len(outputs)} outputs, {len(stale)} ' + ('stale' if args.check else 'updated'))
    return int(args.check and bool(stale))


if __name__ == '__main__':
    raise SystemExit(main())
