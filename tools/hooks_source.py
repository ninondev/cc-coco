"""Find strict hook source while runtime files are generated static facades."""
from pathlib import Path


def source_folder(plugin):
    """plugin/hooks-source in the private tree; source/hooks beside plugin/ in the public one, which moves it out."""
    plugin = Path(plugin)
    for source in (plugin / 'hooks-source', plugin.parent / 'source' / 'hooks'):
        if source.is_dir():
            return source
    return None


def hook_directory(plugin):
    plugin = Path(plugin)
    return source_folder(plugin) or plugin / 'hooks'


def hook_source(path):
    path = Path(path)
    if path.suffix not in {'.ts', '.tsx'} or path.parent.name != 'hooks':
        return path
    source = source_folder(path.parent.parent)
    return source / path.name if source is not None else path


def hook_generated_outputs(outputs):
    """Retain generated data beside canonical TS and its public runtime copy."""
    paired = {}
    for path, value in outputs.items():
        path = Path(path)
        paths = [path]
        if path.suffix in {'.json', '.mjs'} and path.parent.name == 'hooks':
            source = path.parent.parent / 'hooks-source'
            if source.is_dir():
                paths.insert(0, source / path.name)
        for target in paths:
            if target in paired and paired[target] != value:
                raise ValueError('Conflicting generated bytes for ' + str(target))
            paired[target] = value
    return paired
